from enum import Enum


class DeviceStatus(str, Enum):
    ONLINE = "ONLINE"
    OFFLINE = "OFFLINE"
    NEW = "NEW"
    UNKNOWN = "UNKNOWN"


class EventType(str, Enum):
    DEVICE_DISCOVERED = "DEVICE_DISCOVERED"
    DEVICE_CONNECTED = "DEVICE_CONNECTED"
    DEVICE_DISCONNECTED = "DEVICE_DISCONNECTED"
    DEVICE_IP_CHANGED = "DEVICE_IP_CHANGED"
    DEVICE_NAME_CHANGED = "DEVICE_NAME_CHANGED"
    ALWAYS_CONNECTED_DEVICE_DOWN = "ALWAYS_CONNECTED_DEVICE_DOWN"
    ALWAYS_CONNECTED_DEVICE_RECOVERED = "ALWAYS_CONNECTED_DEVICE_RECOVERED"
    # Suspicious identity signals (possible MAC spoofing / IP conflict). Detection only: ARP cannot authenticate.
    DEVICE_ANOMALY = "DEVICE_ANOMALY"
